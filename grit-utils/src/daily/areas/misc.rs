fn setup_synth10k(
    setup: &DailySetup<'_>,
) -> anyhow::Result<super::super::plan::DailyHeadlineContext> {
    let repo = setup_registry_worktree(setup, synth10k_kind(setup.smoke))?;
    crate::worktree_fixture::set_worktree_bench_cwd(&repo)?;
    Ok(ctx(repo, setup))
}

