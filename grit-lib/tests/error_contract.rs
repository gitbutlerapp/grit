/// Size of [`Error`] when the error-contract step landed (area enums must stay ≤ this until step 12).
const ERROR_SIZE_CEILING: usize = 112;

#[test]
fn error_kind_names_are_stable() {
    let mut names: Vec<&'static str> = Vec::new();
    // Sample variants that must keep stable kind slugs when area enums split later.
    names.push(Error::NothingToCommit.kind_name());
    names.push(Error::Cancelled.kind_name());
    names.push(
        Error::NotARepository(grit_lib::error::NotARepositoryReason::NoRepositoryAt {
            path: std::path::PathBuf::from("."),
        })
        .kind_name(),
    );
    for name in names {
        assert!(
            EXPECTED_KIND_NAMES.contains(&name),
            "unexpected kind slug {name}"
        );
    }
    assert_eq!(EXPECTED_KIND_NAMES.len(), 181);
}

#[test]
fn error_type_sizes() {
    let size = std::mem::size_of::<Error>();
    assert_eq!(
        size, ERROR_SIZE_CEILING,
        "update ERROR_SIZE_CEILING in error_contract.rs if the umbrella Error layout changed intentionally"
    );
}
