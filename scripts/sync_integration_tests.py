#!/usr/bin/env python3
"""Write each crate's tests/integration.rs: one module per integration test file.

Cargo builds every tests/*.rs file as its own test executable, and each of them
links all of grit-lib. The crates listed in CRATES set `autotests = false` and
build one executable instead, tests/integration.rs, which includes every test
file in tests/ as a module. Files that must run in their own process (they change
the working directory or environment, or run their own binary again by test
name) stay separate `[[test]]` targets in the crate's Cargo.toml.

Test files that start the system `git` (directly or through a shared helper)
or build heavy fixtures are compiled only with the `full-tests` feature, which
the daily full run enables; scripts/classify_tests.py decides which. The same
goes for separate `[[test]]` targets, which get `required-features`.

Run this after adding, renaming or removing a test file:

    python3 scripts/sync_integration_tests.py

`every_test_file_is_compiled`, a test in each generated file, fails when a test
file is in neither place, so a forgotten file cannot go unrun.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import classify_tests  # noqa: E402

REPO = Path(__file__).resolve().parent.parent
CRATES = [
    "grit-lib",
    "grit-cli",
    "grit-utils",
    "grit-examples",
    "grit-protocol",
    "grit-http-server",
]
ENTRY = "integration.rs"

# Integration modules that must stay in the default suite despite using system git.
DEFAULT_SUITE_OVERRIDE: set[tuple[str, str]] = {
    ("grit-lib", "fetch_reflog_git_compat"),
    ("grit-lib", "reset_hard_at_head_restores_worktree"),
    ("grit-lib", "status_index_refresh_race"),
}
MODULE_CFG_OVERRIDE: dict[tuple[str, str], str] = {
    ("grit-cli", "rebase_exec_interrupt"): "unix",
}

GUARD = '''
/// Fails when a file in `tests/` is neither a module above nor a `[[test]]`
/// target in Cargo.toml: with `autotests = false` cargo would never build it.
#[test]
fn every_test_file_is_compiled() {
    let entry = include_str!("integration.rs");
    let manifest = include_str!("../Cargo.toml");
    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests");
    let mut missing = Vec::new();
    for item in std::fs::read_dir(&dir).expect("read tests/") {
        let name = item.expect("tests/ entry").file_name();
        let Some(name) = name.to_str() else { continue };
        if !name.ends_with(".rs") || name == "integration.rs" {
            continue;
        }
        let module = format!("#[path = \\"{name}\\"]");
        let target = format!("path = \\"tests/{name}\\"");
        if !entry.contains(&module) && !manifest.contains(&target) {
            missing.push(name.to_owned());
        }
    }
    missing.sort();
    assert!(
        missing.is_empty(),
        "tests/{missing:?} would never be built: run `python3 scripts/sync_integration_tests.py` \\
         to add them to tests/integration.rs, or give one a [[test]] entry in Cargo.toml \\
         if it must run in its own process"
    );
}
'''


def separate_targets(manifest: str) -> set[str]:
    """File names of the crate's own `[[test]]` targets, other than the entry."""
    return {
        Path(path).name
        for path in re.findall(r'^path\s*=\s*"tests/([^"]+)"', manifest, re.M)
        if Path(path).name != ENTRY
    }


def module_name(stem: str) -> str:
    return stem.replace("-", "_")


def hoisted_helpers(tests: Path, files: list[Path]) -> list[str]:
    """Helper directories (`tests/<dir>/mod.rs`) that registered files `use crate::<dir>` for."""
    used = set()
    for path in files:
        used.update(re.findall(r"^\s*(?:pub\s+)?use crate::([a-z_0-9]+);", path.read_text(), re.M))
    return sorted(d for d in used if (tests / d / "mod.rs").is_file())


def render(crate: str, modules: list[tuple[str, bool]], helpers: list[str]) -> str:
    lines = [
        "// @generated by scripts/sync_integration_tests.py: run it after adding, renaming",
        "// or removing a file in this directory.",
        "",
        f"//! Every `{crate}` integration test in one test executable, so cargo builds and",
        "//! links one binary instead of one per file. Each file in this directory is a",
        "//! module here, except the `[[test]]` targets in Cargo.toml, which run in their",
        "//! own process.",
        "//!",
        "//! Modules marked `full-tests` start the system `git` or build heavy fixtures;",
        "//! they build only with `--features full-tests` (`make test-full`).",
        "",
    ]
    if helpers:
        lines.append("// Helpers the test modules share, compiled once.")
        lines += [f"mod {h};" for h in helpers]
        lines.append("")
    for stem, full in modules:
        if (crate, stem) in DEFAULT_SUITE_OVERRIDE:
            pass
        elif cfg := MODULE_CFG_OVERRIDE.get((crate, stem)):
            lines.append(f"#[cfg({cfg})]")
        elif full:
            lines.append('#[cfg(feature = "full-tests")]')
        lines.append(f'#[path = "{stem}.rs"]')
        lines.append(f"mod {module_name(stem)};")
    return "\n".join(lines) + "\n" + GUARD


def require_full_tests(manifest: str, full: set[str]) -> str:
    """Give each separate `[[test]]` target in `full` `required-features = ["full-tests"]`."""
    blocks = re.split(r"(?m)^(?=\[)", manifest)
    for i, block in enumerate(blocks):
        m = re.search(r'^path\s*=\s*"tests/([^"]+)"', block, re.M)
        if not block.startswith("[[test]]") or not m or m.group(1) not in full:
            continue
        if "required-features" not in block:
            blocks[i] = block.rstrip("\n") + '\nrequired-features = ["full-tests"]\n' + (
                "\n" if block.endswith("\n\n") else ""
            )
    return "".join(blocks)


def sync(crate: str, shared: set[str]) -> bool:
    root = REPO / crate
    tests = root / "tests"
    cargo = root / "Cargo.toml"
    manifest = cargo.read_text()
    separate = separate_targets(manifest)
    full_separate = {n for n in separate if classify_tests.file_is_full(tests / n, shared)}
    new_manifest = require_full_tests(manifest, full_separate)
    files = sorted(
        p for p in tests.glob("*.rs") if p.name != ENTRY and p.name not in separate
    )
    modules = [(p.stem, classify_tests.file_is_full(p, shared) is not None) for p in files]
    text = render(crate, modules, hoisted_helpers(tests, files))
    entry = tests / ENTRY
    changed = False
    if new_manifest != manifest:
        cargo.write_text(new_manifest)
        changed = True
    if not (entry.is_file() and entry.read_text() == text):
        entry.write_text(text)
        changed = True
    return changed


def main() -> int:
    shared = classify_tests.shared_git_helpers()
    for crate in CRATES:
        if sync(crate, shared):
            print(f"wrote {crate}/tests/{ENTRY}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
