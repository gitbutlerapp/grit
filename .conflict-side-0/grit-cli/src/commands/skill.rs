//! `grit skill` — print an agent skill that explains how to use grit.

use anyhow::Result;
use schemars::JsonSchema;
use serde::Serialize;
use std::io::Write;

use crate::output::{HumanRender, MarkdownRender, RenderContext};
use crate::stdio;

/// The skill text, with `{version}` replaced by the running grit's version.
const SKILL: &str = include_str!("skill.md");

/// Where agents conventionally look for a skill named `grit`.
const SUGGESTED_PATH: &str = ".agents/skills/grit/SKILL.md";

/// Result of `grit skill`.
#[derive(Serialize, JsonSchema)]
pub struct SkillOutcome {
    /// The skill's name, from its front matter.
    pub name: String,
    /// The grit version the skill was generated by.
    pub version: String,
    /// A conventional place to save the skill, relative to a project root.
    pub path: String,
    /// The full `SKILL.md` text, front matter included.
    pub content: String,
}

impl HumanRender for SkillOutcome {
    fn render_human(&self, w: &mut dyn Write, _ctx: &RenderContext) -> Result<()> {
        // Exactly the file bytes, so `grit skill > SKILL.md` works.
        write_skill_content(w, &self.content)
    }
}

impl MarkdownRender for SkillOutcome {
    fn render_markdown(&self, w: &mut dyn Write, _ctx: &RenderContext) -> Result<()> {
        // Same bytes as human mode so agents can save or parse the skill file.
        write_skill_content(w, &self.content)
    }
}

/// Write skill file bytes without adding a trailing newline.
fn write_skill_content(w: &mut dyn Write, content: &str) -> Result<()> {
    stdio::io_result(w.write_all(content.as_bytes()))
        .map_err(|e| anyhow::anyhow!("writing output: {e}"))
}

pub fn run() -> Result<SkillOutcome> {
    let version = env!("CARGO_PKG_VERSION");
    Ok(SkillOutcome {
        name: "grit".to_owned(),
        version: version.to_owned(),
        path: SUGGESTED_PATH.to_owned(),
        content: SKILL.replace("{version}", version),
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn skill_has_front_matter_and_version() {
        let outcome = run().unwrap();
        assert!(outcome
            .content
            .starts_with("---\nname: grit\ndescription: "));
        assert!(!outcome.content.contains("{version}"));
        assert!(outcome.content.contains(env!("CARGO_PKG_VERSION")));
    }

    /// Every `grit <command>` the skill mentions must exist, so the skill can't
    /// drift from the CLI when commands are renamed or removed.
    #[test]
    fn skill_renders_to_string_in_human_and_markdown_modes() {
        use crate::output::{render_to_string, OutputMode};
        use time::OffsetDateTime;

        let outcome = run().unwrap();
        let ctx = RenderContext {
            now: OffsetDateTime::from_unix_timestamp(1_700_000_000).expect("valid timestamp"),
        };
        let human =
            render_to_string(&outcome, OutputMode::Human, &ctx).expect("human render_to_string");
        let markdown = render_to_string(&outcome, OutputMode::Markdown, &ctx)
            .expect("markdown render_to_string");
        assert_eq!(human, outcome.content);
        assert_eq!(markdown, outcome.content);
        assert!(!human.is_empty());
    }

    #[test]
    fn skill_mentions_only_real_commands() {
        crate::cli_test_stack::run(|| {
            use clap::CommandFactory;
            let cli = crate::Cli::command();
            let known: Vec<String> = cli
                .get_subcommands()
                .flat_map(|c| {
                    std::iter::once(c.get_name().to_owned())
                        .chain(c.get_all_aliases().map(str::to_owned))
                })
                .collect();
            let mut missing = Vec::new();
            for (i, _) in SKILL.match_indices("`grit ") {
                let word: String = SKILL[i + 6..]
                    .chars()
                    .take_while(|c| c.is_ascii_alphanumeric() || *c == '-')
                    .collect();
                if !word.is_empty() && !known.contains(&word) {
                    missing.push(word);
                }
            }
            assert!(
                missing.is_empty(),
                "unknown commands in skill.md: {missing:?}"
            );
        });
    }
}
