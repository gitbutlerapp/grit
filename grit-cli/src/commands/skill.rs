//! `grit skill` — print an agent skill that explains how to use grit.

use anyhow::Result;
use schemars::JsonSchema;
use serde::Serialize;
use std::io::Write;

use crate::output::{HumanRender, MarkdownRender, RenderContext};
use crate::stdio;

/// The skill text, with `{version}` replaced by the running grit's version.
const SKILL: &str = include_str!("skill.md");

/// Where agents conventionally look for a skill named `grit`.
const SUGGESTED_PATH: &str = ".agents/skills/grit/SKILL.md";

/// Result of `grit skill`.
#[derive(Serialize, JsonSchema)]
pub struct SkillOutcome {
    /// The skill's name, from its front matter.
    pub name: String,
    /// The grit version the skill was generated by.
    pub version: String,
    /// A conventional place to save the skill, relative to a project root.
    pub path: String,
    /// The full `SKILL.md` text, front matter included.
    pub content: String,
}

impl HumanRender for SkillOutcome {
    fn render_human(&self, w: &mut dyn Write, _ctx: &RenderContext) -> Result<()> {
        // Exactly the file bytes, so `grit skill > SKILL.md` works.
        write_skill_content(w, &self.content)
    }
}

impl MarkdownRender for SkillOutcome {
    fn render_markdown(&self, w: &mut dyn Write, _ctx: &RenderContext) -> Result<()> {
        // Same bytes as human mode so agents can save or parse the skill file.
        write_skill_content(w, &self.content)
    }
}

/// Write skill file bytes without adding a trailing newline.
fn write_skill_content(w: &mut dyn Write, content: &str) -> Result<()> {
    stdio::io_result(w.write_all(content.as_bytes()))
        .map_err(|e| anyhow::anyhow!("writing output: {e}"))
}

pub fn run() -> Result<SkillOutcome> {
    let version = env!("CARGO_PKG_VERSION");
    Ok(SkillOutcome {
        name: "grit".to_owned(),
        version: version.to_owned(),
        path: SUGGESTED_PATH.to_owned(),
        content: SKILL.replace("{version}", version),
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn skill_has_front_matter_and_version() {
        let outcome = run().unwrap();
        assert!(outcome
            .content
            .starts_with("---\nname: grit\ndescription: "));
        assert!(!outcome.content.contains("{version}"));
        assert!(outcome.content.contains(env!("CARGO_PKG_VERSION")));
    }

    /// Every `grit <command>` the skill mentions must exist, so the skill can't
    /// drift from the CLI when commands are renamed or removed.
    #[test]
    fn skill_renders_to_string_in_human_and_markdown_modes() {
        use crate::output::{render_to_string, OutputMode};
        use time::OffsetDateTime;

        let outcome = run().unwrap();
        let ctx = RenderContext {
            now: OffsetDateTime::from_unix_timestamp(1_700_000_000).expect("valid timestamp"),
        };
        let human =
            render_to_string(&outcome, OutputMode::Human, &ctx).expect("human render_to_string");
        let markdown = render_to_string(&outcome, OutputMode::Markdown, &ctx)
            .expect("markdown render_to_string");
        assert_eq!(human, outcome.content);
        assert_eq!(markdown, outcome.content);
        assert!(!human.is_empty());
    }

    #[test]
    fn skill_mentions_only_real_commands() {
        use clap::CommandFactory;

        let cli = crate::cli_command::build_cli_command();
        let known: Vec<String> = cli
            .get_subcommands()
            .flat_map(|c| {
                std::iter::once(c.get_name().to_owned())
                    .chain(c.get_all_aliases().map(str::to_owned))
            })
            .collect();
        let mut missing = Vec::new();
        for (i, _) in SKILL.match_indices("`grit ") {
            let word: String = SKILL[i + 6..]
                .chars()
                .take_while(|c| c.is_ascii_alphanumeric() || *c == '-')
                .collect();
            if !word.is_empty() && !known.contains(&word) {
                missing.push(word);
            }
        }
        assert!(
            missing.is_empty(),
            "unknown commands in skill.md: {missing:?}"
        );
    }

    /// Every flag the skill documents on a grit command path must exist on that clap command.
    #[test]
    fn skill_mentions_only_real_flags() {
        use clap::CommandFactory;

        let root = with_cli_root_for_tests(crate::cli_command::build_cli_command);
        let mut missing = Vec::new();
        for invocation in skill_grit_invocations(SKILL) {
            if invocation.contains('|') || invocation.contains('<') || invocation.contains('>') {
                continue;
            }
            let Some((path, args)) = parse_skill_invocation(&root, &invocation) else {
                continue;
            };
            let Some(cmd) = resolve_command_path(&root, &path) else {
                missing.push(format!("{invocation} (unknown path {path:?})"));
                continue;
            };
            let allowed = allowed_flags(&root, cmd);
            for flag in args {
                if !allowed.contains(&flag) {
                    missing.push(format!("{invocation} (unknown flag {flag})"));
                }
            }
        }
        assert!(
            missing.is_empty(),
            "unknown flags in skill.md:\n{missing:#?}"
        );
    }

    fn with_cli_root_for_tests(
        build: impl FnOnce() -> clap::Command + Send + 'static,
    ) -> clap::Command {
        const STACK: usize = 16 * 1024 * 1024;
        std::thread::Builder::new()
            .stack_size(STACK)
            .spawn(move || build())
            .expect("spawn cli root builder")
            .join()
            .expect("join cli root builder")
    }

    fn skill_grit_invocations(skill: &str) -> Vec<String> {
        let mut out = Vec::new();
        for (i, _) in skill.match_indices("`grit ") {
            let rest = &skill[i + 1..];
            let end = rest.find('`').unwrap_or(rest.len());
            let mut s = rest[..end].to_owned();
            while s.ends_with('*') || s.ends_with(')') || s.ends_with(',') {
                s.pop();
            }
            out.push(s);
        }
        for line in skill.lines() {
            let trimmed = line.trim();
            if let Some(rest) = trimmed.strip_prefix("$ grit ") {
                out.push(format!("grit {rest}"));
            }
        }
        out
    }

    fn parse_skill_invocation(
        root: &clap::Command,
        line: &str,
    ) -> Option<(Vec<String>, Vec<String>)> {
        let tokens = shell_words::split(line).ok()?;
        if tokens.first()?.as_str() != "grit" {
            return None;
        }
        let mut rest = tokens.into_iter().skip(1).peekable();
        let mut path = Vec::new();
        let mut cmd = root;
        while let Some(tok) = rest.peek() {
            if tok.starts_with('-') || tok == "--" {
                break;
            }
            let Some(sub) = cmd.get_subcommands().find(|c| {
                c.get_name() == tok.as_str() || c.get_all_aliases().any(|a| a == tok.as_str())
            }) else {
                break;
            };
            path.push(sub.get_name().to_owned());
            cmd = sub;
            rest.next();
        }
        let mut flags = Vec::new();
        let mut after_paths = false;
        for tok in rest {
            if tok == "--" {
                after_paths = true;
                continue;
            }
            if after_paths || !tok.starts_with('-') {
                continue;
            }
            if tok.starts_with("--") {
                let (name, _) = tok.split_once('=').unwrap_or((&tok, ""));
                flags.push(name.to_owned());
            } else {
                for ch in tok.chars().skip(1) {
                    flags.push(format!("-{ch}"));
                }
            }
        }
        Some((path, flags))
    }

    fn resolve_command_path<'a>(
        root: &'a clap::Command,
        path: &[String],
    ) -> Option<&'a clap::Command> {
        let mut cmd = root;
        for segment in path {
            cmd = cmd
                .get_subcommands()
                .find(|c| c.get_name() == segment.as_str())?;
        }
        Some(cmd)
    }

    fn allowed_flags(root: &clap::Command, leaf: &clap::Command) -> HashSet<String> {
        let mut out = HashSet::new();
        collect_flags(root, &mut out);
        collect_flags(leaf, &mut out);
        out
    }

    fn collect_flags(cmd: &clap::Command, out: &mut HashSet<String>) {
        for arg in cmd.get_arguments() {
            if arg.is_hide_set() {
                continue;
            }
            if let Some(s) = arg.get_short() {
                out.insert(format!("-{s}"));
            }
            if let Some(l) = arg.get_long() {
                out.insert(format!("--{l}"));
            }
            if let Some(aliases) = arg.get_aliases() {
                for alias in aliases {
                    out.insert(format!("--{alias}"));
                }
            }
        }
    }
}
